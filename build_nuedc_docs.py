def font(run, size=10.5, bold=False, color="000000", name="宋体"):
    run.font.name = name
    run._element.get_or_add_rPr().rFonts.set(qn("w:eastAsia"), name)
    run.font.size = Pt(size)
    run.bold = bold
    run.font.color.rgb = RGBColor.from_string(color)

def shade(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = tcPr.find(qn("w:shd"))
    if shd is None:
        shd = OxmlElement("w:shd"); tcPr.append(shd)
    shd.set(qn("w:fill"), fill)

def margins(cell, top=80, start=100, bottom=80, end=100):
    tc = cell._tc.get_or_add_tcPr()
    tcMar = tc.first_child_found_in("w:tcMar")
    if tcMar is None:
        tcMar = OxmlElement("w:tcMar"); tc.append(tcMar)
    for tag, val in (("top",top),("start",start),("bottom",bottom),("end",end)):
        x=tcMar.find(qn("w:"+tag))
        if x is None: x=OxmlElement("w:"+tag); tcMar.append(x)
        x.set(qn("w:w"),str(val)); x.set(qn("w:type"),"dxa")

def base(doc):
    sec=doc.sections[0]
    sec.page_width=Cm(21); sec.page_height=Cm(29.7)
    sec.top_margin=Cm(2.2); sec.bottom_margin=Cm(2.0)
    sec.left_margin=Cm(2.4); sec.right_margin=Cm(2.2)
    sec.header_distance=Cm(1.0); sec.footer_distance=Cm(1.0)
    normal=doc.styles["Normal"]
    normal.font.name="宋体"; normal._element.rPr.rFonts.set(qn("w:eastAsia"),"宋体")
    normal.font.size=Pt(10.5)
    normal.paragraph_format.line_spacing=1.25
    normal.paragraph_format.space_after=Pt(4)
    for nm,size in (("Heading 1",15),("Heading 2",12.5),("Heading 3",11)):
        s=doc.styles[nm]; s.font.name="黑体"; s._element.rPr.rFonts.set(qn("w:eastAsia"),"黑体")
        s.font.size=Pt(size); s.font.bold=True; s.font.color.rgb=RGBColor.from_string(BLUE)
        s.paragraph_format.space_before=Pt(10); s.paragraph_format.space_after=Pt(5)
    footer=sec.footer.paragraphs[0]; footer.alignment=WD_ALIGN_PARAGRAPH.CENTER
    r=footer.add_run("全国大学生电子设计竞赛 · 小车题报告工作稿"); font(r,8,color="777777")

def title(doc, text, subtitle):
    p=doc.add_paragraph(); p.alignment=WD_ALIGN_PARAGRAPH.CENTER; p.paragraph_format.space_before=Pt(70)
    r=p.add_run(text); font(r,24,True,BLUE,"黑体")
    p=doc.add_paragraph(); p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    r=p.add_run(subtitle); font(r,13,False,"555555","黑体")
    doc.add_paragraph("")

def h(doc, text, level=1): doc.add_heading(text, level=level)

def para(doc, text, bold_prefix=None):
    p=doc.add_paragraph()
    if bold_prefix and text.startswith(bold_prefix):
        r=p.add_run(bold_prefix); font(r,10.5,True)
        r=p.add_run(text[len(bold_prefix):]); font(r)
    else:
        r=p.add_run(text); font(r)
    return p

def bullet(doc, text):
    p=doc.add_paragraph(style="List Bullet"); font(p.add_run(text))

def table(doc, headers, rows, widths=None):
    t=doc.add_table(rows=1, cols=len(headers)); t.alignment=WD_TABLE_ALIGNMENT.CENTER
    t.style="Table Grid"; t.autofit=False
    for i,x in enumerate(headers):
        c=t.rows[0].cells[i]; shade(c,BLUE); margins(c); c.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
        p=c.paragraphs[0]; p.alignment=WD_ALIGN_PARAGRAPH.CENTER; font(p.add_run(x),9,True,"FFFFFF","黑体")
    for row in rows:
        cells=t.add_row().cells
        for i,x in enumerate(row):
            c=cells[i]; margins(c); c.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            if len(t.rows)%2==1: shade(c,GRAY)
            p=c.paragraphs[0]; font(p.add_run(str(x)),9)
    if widths:
        for row in t.rows:
            for i,w in enumerate(widths): row.cells[i].width=Cm(w)
    doc.add_paragraph("")
    return t

def callout(doc, label, text, color=LIGHT):
    t=doc.add_table(rows=1, cols=1); t.style="Table Grid"; t.alignment=WD_TABLE_ALIGNMENT.CENTER
    c=t.cell(0,0); shade(c,color); margins(c,120,160,120,160)
    p=c.paragraphs[0]; font(p.add_run(label+"："),10.5,True,BLUE,"黑体"); font(p.add_run(text),10.5)
    doc.add_paragraph("")

